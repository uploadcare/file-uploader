export function resolveEditorL10n(overrides?: Record<string, string>): EditorL10n {
  return (key, variables = {}) => {
    const template = overrides?.[key] ?? EDITOR_DEFAULT_LOCALE[key] ?? key;
    return applyTemplateData(template, variables);
  };
}
